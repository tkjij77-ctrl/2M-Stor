export type StoreInfo = {
  store?: string;
  phone?: string;
  address?: string;
  desc?: string;
  /** 0 = لم تُحدَّد سياسة إرجاع بعد */
  returnDays?: number;
  returnNote?: string;
};

/** صياغة عربية سليمة للمدة: «يوم واحد» · «يومان» · «7 أيام» · «14 يومًا» */
export function daysWord(n: number): string {
  if (n === 1) return "يوم واحد";
  if (n === 2) return "يومان";
  if (n >= 3 && n <= 10) return `${n} أيام`;
  if (n >= 11 && n <= 99) return `${n} يومًا`;
  return `${n} يوم`;
}

/** نص سياسة الإرجاع — لا يَعِد إلا بما حُدِّد فعلًا في الإعدادات */
export function returnPolicyText(info: StoreInfo): string {
  const days = Number(info.returnDays) || 0;
  const note = (info.returnNote || "").trim();

  if (days <= 0 && !note) {
    return "لم تُحدَّد سياسة إرجاع بعد. تواصل مع المتجر قبل الشراء لمعرفة الشروط.";
  }

  // شروط المالك تُدمج في الجملة نفسها (لا جملة مقتطعة بعد نقطة)
  if (days > 0) {
    return (
      `يمكن الإرجاع خلال ${daysWord(days)} من تاريخ الفاتورة` +
      (note ? `، ${note}` : "، بشرط أن يكون الصنف بحالته الأصلية.")
    );
  }
  return note;
}

/** بيانات التواصل — لا تُعرض أرقام أو عناوين غير حقيقية */
export function contactLines(info: StoreInfo): string[] {
  const out: string[] = [];
  if (info.phone && info.phone.trim()) out.push("📞 " + info.phone.trim());
  if (info.address && info.address.trim()) out.push("📍 " + info.address.trim());
  return out;
}

